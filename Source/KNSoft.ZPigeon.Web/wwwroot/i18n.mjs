const requested = navigator.languages?.find((value) => /^zh\b|^en\b/i.test(value)) || navigator.language;
export const language = /^zh\b/i.test(requested) ? "zh-CN" : "en-US";
const sourceKeys = new Map(Object.entries(zh).map(([key, value]) => [value, key]));
document.documentElement.lang = language;

export function translate(targetLanguage, key, values) {
  const messages = targetLanguage === "zh-CN" ? zh : en;
  let value = messages[key] ?? zh[key] ?? key;
  if (values)
    for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`, replacement);
  return value;
}

export function t(key, values) {
  return translate(language, key, values);
}

